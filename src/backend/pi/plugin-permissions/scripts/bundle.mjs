// Builds the plugin OpenGhost ships: dist/plugin-permissions.js (the sources
// and their npm dependencies in one ES module) beside the two WASM grammars
// the bash parser loads. Pi's own packages stay external: Pi provides them to
// every extension it loads. Run with `npm run bundle` after `npm ci`; the
// output is committed, so building OpenGhost needs no Node. `--out <dir>`
// writes elsewhere (the freshness check builds into a scratch directory).
import { copyFileSync, mkdirSync, readFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";
import { build } from "esbuild";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const at = process.argv.indexOf("--out");
const dist = at > 0 ? process.argv[at + 1] : join(root, "dist");
const { version } = JSON.parse(readFileSync(join(root, "package.json"), "utf8"));
mkdirSync(dist, { recursive: true });

await build({
  entryPoints: [join(root, "src", "index.ts")],
  outfile: join(dist, "plugin-permissions.js"),
  bundle: true,
  platform: "node",
  format: "esm",
  target: "node22",
  external: ["@earendil-works/*"],
  legalComments: "inline",
  charset: "utf8",
  banner: {
    js: [
      `// plugin-permissions ${version}: OpenGhost's Pi permission plugin. Generated by`,
      "// scripts/bundle.mjs from src/; do not edit. Derived from",
      "// @gotgenes/pi-permission-system 40.0.0 (MIT, Copyright (c) 2026 MasuRii and",
      "// Christopher D. Lasher). Bundles zod, web-tree-sitter and tree-sitter-bash (MIT).",
      "// See LICENSE and THIRD_PARTY_LICENSES.md beside the sources.",
    ].join("\n"),
  },
  logLevel: "warning",
});

for (const [from, to] of [
  ["web-tree-sitter/web-tree-sitter.wasm", "web-tree-sitter.wasm"],
  ["tree-sitter-bash/tree-sitter-bash.wasm", "tree-sitter-bash.wasm"],
]) {
  copyFileSync(join(root, "node_modules", from), join(dist, to));
}
